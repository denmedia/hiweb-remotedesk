package com.hiweb.hiwebremotedesk.ui

import com.hiweb.hiwebremotedesk.agent.AgentPower
import com.hiweb.hiwebremotedesk.data.OsType
import com.hiweb.hiwebremotedesk.data.PcState

/** Пояснение к неактивной кнопке карточки ПК: что произошло и что сделать, чтобы она заработала. */
data class ButtonHint(val title: String, val text: String)

/** Тексты подсказок для неактивных кнопок списка ПК (чистая логика — под юнит-тестами). */
object ButtonHints {
    private const val INSTALL_AGENT =
        "Откройте сеанс на этом ПК и нажмите на панели сеанса «Установить агент» (или «Обновить агент»), затем " +
            "подтвердите запуск на ПК. Агент сам свяжется с планшетом по сети."

    /** «Подключиться» / «Разбудить» неактивна: ПК не в сети, и разбудить его по сети нельзя. */
    fun connect(state: PcState): ButtonHint = when (state) {
        PcState.SLEEP, PcState.HIBERNATE -> ButtonHint(
            "Нельзя разбудить ПК",
            "ПК в режиме «${state.title}». Чтобы будить его по сети, откройте «Настройки» этой карточки и " +
                "укажите MAC-адрес в поле «MAC-адрес для пробуждения по сети» (он заполняется сам, когда на ПК работает " +
                "агент и ПК был в сети). Либо разбудите ПК вручную.",
        )
        PcState.RESTARTING -> ButtonHint("ПК перезагружается", "Подождите минуту: кнопка станет активной, когда ПК снова будет в сети.")
        else -> ButtonHint(
            "ПК недоступен",
            "Сейчас ПК «${state.title.lowercase()}». Включите его и проверьте, что он в той же сети, что и планшет, " +
                "а адрес в «Настройках» карточки верный. Чтобы включать ПК с планшета, укажите там MAC-адрес для пробуждения по сети.",
        )
    }

    /** Кнопка питания без агента: действие идёт через сеанс RDP/SSH, поэтому ПК должен быть включён. */
    fun sessionPower(state: PcState): ButtonHint = ButtonHint(
        "ПК недоступен",
        "Эта команда отправляется через подключение к ПК, а он сейчас «${state.title.lowercase()}». " +
            "Включите ПК — кнопка станет активной, когда он появится в сети.",
    )

    /**
     * Кнопка режима питания неактивна.
     * [agentOnline] — агент на связи; [pcUp] — ПК отвечает. С агентом на связи кнопка неактивна, если режим он не назвал доступным.
     */
    fun power(os: OsType, action: AgentPower, agentOnline: Boolean, pcUp: Boolean, state: PcState): ButtonHint {
        if (os != OsType.WINDOWS && (action == AgentPower.SLEEP || action == AgentPower.HIBERNATE)) {
            return ButtonHint("Недоступно для Ubuntu", "Сон и гибернация работают только через HiWeb Agent на Windows. " +
                "Для Ubuntu доступны перезагрузка и выключение по SSH.")
        }
        if (!agentOnline) {
            return if (pcUp) {
                ButtonHint("Агент не на связи", "${action.title} выполняет HiWeb Agent на ПК, но он сейчас не подключён к планшету. " +
                    "Если агент не установлен: $INSTALL_AGENT Если установлен — проверьте, что он запущен (значок ноутбука в трее) " +
                    "и ПК в той же сети. Кнопка станет активной сама, как только агент выйдет на связь.")
            } else {
                ButtonHint("Агент не на связи", "ПК сейчас «${state.title.lowercase()}», поэтому агент не подключён. " +
                    "Кнопка станет активной, когда ПК включится и агент выйдет на связь.")
            }
        }
        return when (action) {
            AgentPower.HIBERNATE -> ButtonHint(
                "Гибернация выключена в Windows",
                "Агент сообщил, что гибернация на ПК недоступна. Включите её: откройте на ПК командную строку от " +
                    "администратора и выполните powercfg /hibernate on. Кнопка станет активной сама.",
            )
            AgentPower.SLEEP -> ButtonHint(
                "Сон недоступен на ПК",
                "Агент сообщил, что Windows не поддерживает сон на этом ПК: он отключён политикой или не поддерживается " +
                    "оборудованием и драйверами (проверьте настройки электропитания и BIOS).",
            )
            else -> ButtonHint("Действие недоступно", "Агент сообщил, что Windows не разрешает «${action.title.lowercase()}» на этом ПК.")
        }
    }

    /** Щит защиты подключений неактивен: агент не присылал данных. */
    fun guard(): ButtonHint = ButtonHint(
        "Защита подключений недоступна",
        "Журнал входов и защиту RDP присылает HiWeb Agent версии 1.8 и новее, а от этого ПК данных ещё нет. " +
            INSTALL_AGENT + " Если агент уже стоит, дождитесь, когда ПК будет в сети.",
    )
}
